function safeWrite(tree: Tree, path: string, content: string): void {
  assertWritePathAllowed(path.replace(/\\/g, "/"));
  tree.write(path, content);
}

function appendBeforeMarker(content: string, marker: string, insertion: string): string {
  const trimmed = insertion.trim();
  if (trimmed && content.includes(trimmed)) {
    return content;
  }
  const idx = content.indexOf(marker);
  if (idx === -1) {
    throw new Error(`Marker not found: ${marker}`);
  }
  return `${content.slice(0, idx)}${insertion}\n${content.slice(idx)}`;
}

function stubProviderSource(args: {
  className: string;
  fileName: string;
  platformId: string;
}): string {
  return `import type {
  GetTasksOptions,
  PlatformProject,
  PlatformTask,
  TaskPlatformProvider,
} from "@sai-mp-jira-task-view/platform";

import type { JiraBffTransportOptions } from "@sai-mp-jira-task-view/jira-providers";

/**
 * Generated stub for "${args.platformId}" (Phase 6.2 platform-app).
 * Replace with real BFF integration; keep {@link TaskPlatformProvider} contract.
 */
export class ${args.className}TaskPlatformProvider implements TaskPlatformProvider {
  constructor(_options?: JiraBffTransportOptions) {}

  async getProjects(): Promise<PlatformProject[]> {
    return [];
  }

  async getTasks(_projectKey: string, _options?: GetTasksOptions): Promise<PlatformTask[]> {
    return [];
  }
}
`;
}

function capabilityBlockSource(className: string, platformId: string, kind: PlatformKind): string {
  const flags = getGeneratedCapabilityFlags(kind);
  const lines = Object.entries(flags)
    .map(([k, v]) => `      "${k}": ${v},`)
    .join("\n");
  return `import type { PlatformCapabilities } from "../capability-types";

export const ${className}Capabilities: PlatformCapabilities = {
  platform: "${platformId}",
  version: "1.0",
  capabilities: {
${lines}
  },
};
`;
}

function uiSchemaEntry(platformId: string): string {
  return `  ${platformId}: {
    type: "container",
    children: [
      { type: "feature", key: "tasks.status" },
      { type: "feature", key: "tasks.assign" },
    ],
  },`;
}

function platformConfigSource(platformId: string): string {
  return `export const PLATFORM_CONFIG = {
  platform: "${platformId}",
  capabilities: "auto" as const,
} as const;
`;
}

function envTemplateSource(platformId: string): string {
  const p = platformId.toUpperCase().replace(/[^A-Z0-9]/g, "_");
  return `# ${platformId} — generated by platform-generator (Phase 6.2)
# OAuth (example keys)
${p}_CLIENT_ID=
${p}_CLIENT_SECRET=

# API base URL
${p}_API_BASE_URL=

# Supabase (optional)
NEXT_PUBLIC_SUPABASE_URL=
NEXT_PUBLIC_SUPABASE_ANON_KEY=
`;
}

